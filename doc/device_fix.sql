-- ----------------------------------------------------------------------------
-- 设备档案表 device_no 唯一性修复脚本（面向已上线的库，手工执行一次）
--
-- 背景：
--   t_sys_device 建表脚本 doc/device.sql 里声明了唯一索引 uk_device_no，
--   但线上表很可能未建成/未执行，导致同一设备编号可重复入库。
--   由此带来两个表象：
--     1) 新增同编号设备不报重复；
--     2) 删除某台设备后，同编号的另一条“影子”仍在列表里，看起来像没删掉。
--
-- 本脚本处理：
--   ① 去掉编号首尾空格；
--   ② 清理重复记录，每个 device_no 仅保留 id 最小（最早创建）的一条；
--   ③ 为 device_no 重建唯一索引（数据库层硬约束，杜绝再次重复）。
--
-- 建议执行顺序（重要）：
--   先跑“1. 预览”确认将删除哪些行；再执行 2/3/4。
-- ----------------------------------------------------------------------------

-- ----------------------------------------------------------------------------
-- 1. 预览：查看当前重复的编号及会被清理的行
--    每行 device_no 只保留 id 最小的一条，其余同编号记录将被删除。
-- ----------------------------------------------------------------------------
SELECT t1.*
FROM t_sys_device t1
JOIN t_sys_device t2
  ON t1.device_no = t2.device_no AND t1.id > t2.id;

-- 分组重复统计
SELECT device_no, COUNT(*) AS cnt
FROM t_sys_device
GROUP BY device_no
HAVING COUNT(*) > 1;

-- ----------------------------------------------------------------------------
-- 2. 去空格：避免 “DP-2001” 与 “ DP-2001 ” 等被当成不同编号
-- ----------------------------------------------------------------------------
UPDATE t_sys_device SET device_no = TRIM(device_no);

-- ----------------------------------------------------------------------------
-- 3. 清理重复：每个 device_no 保留 id 最小的一条
--    （先备份：mysqldump 或自行导出后再执行）
-- ----------------------------------------------------------------------------
DELETE t1
FROM t_sys_device t1
JOIN t_sys_device t2
  ON t1.device_no = t2.device_no AND t1.id > t2.id;

-- ----------------------------------------------------------------------------
-- 4. 重建唯一索引 uk_device_no（数据库层硬约束）
--    若上一步仍有重复未清干净，本步会报错，请回到步骤 1/3 检查。
-- ----------------------------------------------------------------------------
ALTER TABLE t_sys_device DROP INDEX uk_device_no;
ALTER TABLE t_sys_device ADD UNIQUE KEY uk_device_no (device_no);

-- ----------------------------------------------------------------------------
-- 5. 校验：
--    以下查询应分别返回 0 行 / 空结果，说明编号已全部唯一
-- ----------------------------------------------------------------------------
SELECT device_no, COUNT(*) AS cnt
FROM t_sys_device
GROUP BY device_no
HAVING COUNT(*) > 1;

SHOW INDEX FROM t_sys_device;
